const general = new Map(GENERAL_WORDS.map((word) => [word.id, word]));
export const TOPIC_PACKS_BY_ID = new Map(TOPIC_PACKS.map((pack) => [pack.id, pack]));

export function topicWords(packId: string): Word[] {
  const pack = TOPIC_PACKS_BY_ID.get(packId);
  if (!pack) throw new Error(`Unknown topic pack: ${packId}`);
  return pack.wordIds.map((id) => {
    const word = general.get(id);
    if (!word) throw new Error(`Topic word is not in the approved general vocabulary: ${id}`);
    return { ...word, category: `主题包 · ${pack.name}` };
  });
}

export const TOPIC_WORDS = TOPIC_PACKS.flatMap((pack) => topicWords(pack.id));
