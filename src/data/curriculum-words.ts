function parseBlock(grade: number, block: string): Word[] {
  return block
    .trim()
    .split('\n')
    .map((line) => {
      const [en, zh, emoji = ''] = line.split('|');
      return {
        id: en
          .toLowerCase()
          .replace(/[^a-z0-9]+/g, '-')
          .replace(/^-|-$/g, ''),
        en,
        zh,
        emoji,
        phonetic: '',
        category: `${grade} 年级课标参考`,
      } satisfies Word;
    });
}

export const GRADE_BANDS: Record<number, Word[]> = {
  1: [...WORDS, ...parseBlock(1, firstGradeAdditions)],
  2: parseBlock(2, secondGradeWords),
  3: parseBlock(3, thirdGradeWords),
  4: parseBlock(4, fourthGradeWords),
  5: parseBlock(5, fifthGradeWords),
  6: parseBlock(6, sixthGradeWords),
};

export const GENERAL_GRADES = [1, 2, 3, 4, 5, 6] as const;
export const GENERAL_WORDS_BY_GRADE: Record<number, Word[]> = Object.fromEntries(
  GENERAL_GRADES.map((grade) => [
    grade,
    GENERAL_GRADES.filter((item) => item <= grade).flatMap((item) => GRADE_BANDS[item]),
  ]),
);
export const GENERAL_WORDS = GENERAL_GRADES.flatMap((grade) => GRADE_BANDS[grade]);
