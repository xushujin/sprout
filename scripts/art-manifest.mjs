import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { readdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

/**
 * Content revision of the whole illustration set. `/art/*` is cached for a
 * week, so the fixed filenames alone would keep serving the previous drawings
 * from the edge and from returning browsers long after a repaint. Appending
 * this hash as a query string gives every repaint a fresh URL while the long
 * cache still applies in between.
 */
export function artRevision(root) {
  const artDir = resolve(root, 'public/art');
  const wordDir = resolve(root, 'public/art/words');
  const scenes = existsSync(artDir)
    ? readdirSync(artDir)
        .filter((file) => file.endsWith('.webp'))
        .sort()
    : [];
  const words = existsSync(wordDir)
    ? readdirSync(wordDir)
        .filter((file) => file.endsWith('.webp') && statSync(resolve(wordDir, file)).size >= 2_000)
        .sort()
    : [];

  const hash = createHash('md5');
  for (const name of scenes) {
    hash.update(name);
    hash.update(readFileSync(resolve(artDir, name)));
  }
  for (const name of words) {
    hash.update(name);
    hash.update(readFileSync(resolve(wordDir, name)));
  }
  return hash.digest('hex').slice(0, 8);
}

/** Rewrites src/data/word-images.ts from the files that actually exist. */
export async function writeWordManifest(root) {
  const wordDir = resolve(root, 'public/art/words');
  const words = existsSync(wordDir)
    ? (await readdir(wordDir))
        .filter((file) => file.endsWith('.webp') && statSync(resolve(wordDir, file)).size >= 2_000)
        .sort()
    : [];
  const ids = words.map((file) => file.replace(/\.webp$/, ''));
  const rev = artRevision(root);
  const target = resolve(root, 'src/data/word-images.ts');
  const source = `// Generated by scripts/generate-art*.mjs. Do not edit by hand.
// Only words with a reviewed illustration are listed; everything else keeps
// its emoji so a picture question never shows a broken image.
export const WORD_ART_IDS = [
${ids.map((id) => `  '${id}',`).join('\n')}
] as const;

/** Content revision of the illustration set; changes whenever a file does. */
export const ART_REV = '${rev}';

const WORD_ART = new Set<string>(WORD_ART_IDS);

/** Public URL for a word illustration, or undefined when it has none. */
export function wordImage(id: string): string | undefined {
  return WORD_ART.has(id) ? \`/art/words/\${id}.webp?v=\${ART_REV}\` : undefined;
}
`;
  await writeFile(target, source);
  console.log(`词画清单已更新：${ids.length} 个单词，版本 ${rev} → ${target}`);
}

// `npm run art:manifest` bumps the revision after replacing files by hand.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  await writeWordManifest(root);
}
